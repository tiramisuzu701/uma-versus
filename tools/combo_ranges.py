# Measures, for every combo route the CPU can use, the largest starting distance from which every hit
# connects on a standing opponent (with Spurt for EX, and without), and the damage it does. Writes src/ranges.js.
# Re-run after changing moves.
import asyncio, json, subprocess
from playwright.async_api import async_playwright
JS = r"""() => {
  const out = {};
  function tryRoute(cid, t, dist, meter, crouch) {
    startMatch('cpu', cid, 'spe'); G.phase = 'fight'; G.p.forEach(p => p.setState('idle'));
    const me = G.p[0], d = G.p[1], x0 = t.corner ? STAGE_W - 185 - dist : 900;   // corner routes: same spot as the trials
    me.x = x0; d.x = x0 + dist; me.facing = 1; d.facing = -1; me.meter = meter; G.cam = Math.max(W / 2, Math.min(STAGE_W - W / 2, (me.x + d.x) / 2));
    aiState(me); aiStartRun(me, t.seq, CPU_LV[4]); me.ai.run.superRoll = false;   // measure the route itself, not a super finish
    const want = me.ai.run.toks.filter(x => x !== 'jc' && x !== 'dc').length;
    let inst = null, pm = null, pt = 0, hits = 0, broke = false, started = false, sup = false;
    for (let f = 0, after = 0; f < 500 && after < 90; f++) {   // keep going a little after the route ends so its last hit can land
      if (!me.ai.run) after++;
      const i = (me.ai.run && aiRunInput(me, d, CPU_LV[4])) || { ...NEUTRAL };
      step([i, crouch ? { ...NEUTRAL, d: 1 } : { ...NEUTRAL }]);
      if (me.state === 'attack' && (me.move !== pm || me.t < pt)) inst = { hit: false };
      pm = me.state === 'attack' ? me.move : null; pt = me.t;
      if (inst && !inst.hit && me.state === 'attack' && me.hitOK) { inst.hit = true; hits++; }
      if (me.state === 'cine' || (me.state === 'attack' && me.move.kind === 'super' && me.hitOK)) sup = true;   // finishing with the super instead counts
      if (d.combo > 0) started = true; else if (started && hits < want && !sup) broke = true;
    }
    return (hits >= want || sup) && !broke ? d.c.hp - d.hp : 0;
  }
  for (const cid of ROSTER) {
    out[cid] = {};
    for (const t of trialsFor(cid)) {
      if (t.seq.startsWith('j.')) continue;
      const ex = /\d{3,5}H/.test(t.seq);   // uses an EX skill
      let r = 0, rx = 0, dmg = 0, dmgx = 0;
      for (let dist = 60; dist <= 320; dist += 10) { const v = tryRoute(cid, t, dist, 100); if (v) { rx = dist; if (!dmgx) dmgx = v; } else break; }
      if (!ex) { r = rx; dmg = dmgx; }
      else for (let dist = 60; dist <= 320; dist += 10) { const v = tryRoute(cid, t, dist, 30); if (v) { r = dist; if (!dmg) dmg = v; } else break; }
      // the same against someone crouching (with the meter the CPU would have for it)
      let rc = 0;
      for (let dist = 60; dist <= 320; dist += 10) { if (tryRoute(cid, t, dist, ex ? 100 : 30, true)) rc = dist; else break; }
      out[cid][t.seq] = { r, rx, rc, dmg, dmgx, ex };
    }
  }
  return JSON.stringify(out);
}"""
async def main():
    subprocess.run(['python3', ROOT+'/tools/build.py'], check=True)
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('file://' + ROOT + '/build/uma-versus.html', wait_until='domcontentloaded', timeout=120000); await pg.wait_for_timeout(3000)
        await pg.evaluate("() => { tick = () => {}; render = () => {}; Sfx.play = () => {}; }")
        res = json.loads(await pg.evaluate(JS))
        print('ERR', errs[:3]); await b.close()
    lines = ["// generated by tools/combo_ranges.py: for each CPU route, how far away it can start and still connect every",
             "// hit (r: without Spurt, rx: with Spurt for EX, rc: on a crouching opponent), and its damage (dmg / dmgx). ex: the route uses an EX skill.",
             "'use strict';", "const COMBO_RANGE = {"]
    for cid, r in res.items():
        lines.append(f"  {cid}: {{")
        for k, v in r.items(): lines.append(f"    {json.dumps(k)}: {json.dumps(v, separators=(',', ':'))},")
        lines.append("  },")
    lines.append("};")
    open(ROOT+'/src/ranges.js', 'w').write('\n'.join(lines) + '\n')
    for cid, r in res.items(): print(cid, r)
    subprocess.run(['python3', ROOT+'/tools/build.py'], check=True)
asyncio.run(main())
